import { type DB, nowIso } from '../db.js';
import { actionPlan, activeHandoff, contacts, eveningLog, events, familyNames, household, visibleFacts, whereIs } from './house.js';
import { emergencyKind, type EmergencyKind } from './safety.js';
import { incidentView, openIncident } from './incident.js';

interface Script {
  say_first: string;
  source: string;
  steps: Array<{ step: number; text: string; timer_seconds: number | null }>;
  show_epipen: boolean;
}

const steps = (texts: string[]) => texts.map((text, i) => ({ step: i + 1, text, timer_seconds: null }));
const DISPATCHER = 'Stay on the line. The 911 dispatcher will tell you exactly what to do until help arrives.';

/**
 * Picks the script for the kind of emergency. The parents' own action plan is used for
 * allergy and breathing emergencies; everything else gets general safety steps that send
 * the carer to 911 or Poison Control. Nothing here is medical advice of our own.
 */
function scriptFor(kind: EmergencyKind, child: string, plan: ReturnType<typeof actionPlan>): Script {
  const call911 = 'Call 911 now on your phone. Tell them the address on the screen.';
  switch (kind) {
    case 'allergy_breathing':
      if (plan.length) {
        return {
          say_first: call911,
          source: "From the doctor's plan the parents saved. Read it exactly as written.",
          steps: plan.map((s) => ({ step: s.step_no, text: s.text, timer_seconds: s.timer_seconds })),
          show_epipen: true,
        };
      }
      return { say_first: call911, source: 'General safety steps', steps: steps([call911, DISPATCHER]), show_epipen: false };
    case 'fire':
      return {
        say_first: `Get everyone out of the house now, then call 911 from outside.`,
        source: 'General safety steps',
        steps: steps([
          `Get ${child} and everyone else out now. Don't stop for belongings.`,
          'Close doors behind you if you can.',
          'Call 911 from outside and give the address.',
          "Don't go back inside.",
        ]),
        show_epipen: false,
      };
    case 'gas':
      return {
        say_first: 'Get everyone out of the house now, then call 911 from outside.',
        source: 'General safety steps',
        steps: steps([
          `Get ${child} and everyone else out now.`,
          "Don't switch lights or appliances on or off, and don't use a lighter or matches.",
          'Call 911 from outside and give the address.',
        ]),
        show_epipen: false,
      };
    case 'poison':
      return {
        say_first: "Call Poison Control now at 1-800-222-1222. If the child isn't breathing or won't wake up, call 911 instead.",
        source: 'General safety steps',
        steps: steps([
          `If ${child} isn't breathing, won't wake up or is having a seizure, call 911.`,
          'Otherwise call Poison Control now: 1-800-222-1222.',
          'Keep the container or packet so you can tell them what it was.',
        ]),
        show_epipen: false,
      };
    case 'intruder':
      return {
        say_first: `Take ${child} to a room you can lock and call 911.`,
        source: 'General safety steps',
        steps: steps([`Take ${child} to a room you can lock and stay quiet.`, 'Call 911 and give the address.', "Don't confront anyone."]),
        show_epipen: false,
      };
    case 'missing':
      return {
        // the same words as step 1, so the guide says them once
        say_first: `Call 911 now. Say ${child} is missing and describe what ${child} is wearing.`,
        source: 'General safety steps',
        steps: steps([
          `Call 911 now. Say ${child} is missing and describe what ${child} is wearing.`,
          'Check the house and the yard while you wait, including small spaces.',
          DISPATCHER,
        ]),
        show_epipen: false,
      };
    default:
      return { say_first: call911, source: 'General safety steps', steps: steps([call911, DISPATCHER, `Don't leave ${child} alone.`]), show_epipen: false };
  }
}

/**
 * The emergency response is a FIXED script assembled from the parents' own data and general
 * safety steps. Nothing here is generated by an AI model.
 */
export function startEmergency(db: DB, description: string) {
  const home = household(db);
  const facts = visibleFacts(db, 'carer');
  const chain = contacts(db).filter((c) => c.priority < 9);
  const doctor = contacts(db).find((c) => c.priority >= 9);
  const epipen = whereIs(db, 'EpiPen');
  const h = activeHandoff(db);
  const log = eveningLog(db);
  const child = (db.prepare("SELECT name FROM members WHERE kind = 'child' ORDER BY id LIMIT 1").get() as { name: string } | undefined)?.name ?? 'the child';
  const kind = emergencyKind(description, familyNames(db)) ?? 'general';
  const script = scriptFor(kind, child, actionPlan(db));

  const alert = {
    at: nowIso(),
    description,
    kind,
    carer: h?.carer_name ?? null,
    notified: chain.map((c) => `${c.name} (${c.relation})`),
  };
  events.emit('emergency', alert);

  const result = {
    kind,
    say_first: script.say_first,
    address: home?.address ?? null,
    action_plan: { source: script.source, steps: script.steps },
    epipen_location: script.show_epipen ? epipen?.description ?? null : null,
    epipen_photo: script.show_epipen ? epipen?.photo_url ?? null : null,
    parents_alerted: alert.notified,
    paramedic_sheet: {
      allergies: facts.filter((f) => f.category === 'allergy').map((f) => f.text),
      medicine_notes: facts.filter((f) => f.category === 'medicine').map((f) => f.text),
      doctor: doctor ? `${doctor.name}, ${doctor.phone}` : null,
      tonight: log.map((e) => ({ at: e.at, text: e.text })),
      reported: { at: alert.at, text: description },
    },
    // Alexa+ policy: never claim to call for help or to save a life; medical steps are attributed.
    note: "This device can't call 911: use your phone. These steps are the family's own plan and general safety steps, not a substitute for professional medical advice.",
  };
  // The guide that walks the carer through it, one step at a time, with the plan's timers.
  const incident = openIncident(db, { kind, description, steps: script.steps.map((s) => ({ text: s.text, timer_seconds: s.timer_seconds })), script: result });
  return { ...result, incident: incidentView(db, incident) };
}

/**
 * Every guide at once, for the sitter's phone to keep: if the internet drops, the phone still has
 * the parents' plan and the safety steps for each kind of emergency (and phone calls still work).
 */
export function offlineGuides(db: DB) {
  const child = (db.prepare("SELECT name FROM members WHERE kind = 'child' ORDER BY id LIMIT 1").get() as { name: string } | undefined)?.name ?? 'the child';
  const plan = actionPlan(db);
  const KINDS: Array<[EmergencyKind, string]> = [
    ['allergy_breathing', 'Allergic reaction or trouble breathing'],
    ['choking', 'Choking'],
    ['fire', 'Fire or smoke'],
    ['gas', 'Smell of gas'],
    ['poison', 'Swallowed something harmful'],
    ['missing', `Can't find ${child}`],
    ['intruder', 'Someone breaking in'],
    ['general', 'Anything else'],
  ];
  return KINDS.map(([kind, label]) => {
    const s = scriptFor(kind, child, plan);
    return { kind, label, say_first: s.say_first, source: s.source, steps: s.steps.map((x) => x.text), poison_line: kind === 'poison' ? '1-800-222-1222' : null };
  });
}
